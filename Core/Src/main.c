/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  LL_APB2_GRP1_EnableClock(LL_APB2_GRP1_PERIPH_AFIO);
  LL_APB1_GRP1_EnableClock(LL_APB1_GRP1_PERIPH_PWR);

  /* System interrupt init*/
  NVIC_SetPriorityGrouping(NVIC_PRIORITYGROUP_4);

  /* SysTick_IRQn interrupt configuration */
  NVIC_SetPriority(SysTick_IRQn, NVIC_EncodePriority(NVIC_GetPriorityGrouping(),15, 0));

  /** NOJTAG: JTAG-DP Disabled and SW-DP Enabled
  */
  LL_GPIO_AF_Remap_SWJ_NOJTAG();

  /* USER CODE BEGIN Init */
  
  // uint32_t u32LED0_Tick = 0; // 紀錄上一次LED0動作的時間
  ekeyKeyEvent ekeyEvent0;
  ekeyKeyEvent ekeyEvent1;
  eusartUSART_Cmd eusartCMD;
  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */
  LL_SYSTICK_EnableIT();
  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART1_UART_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */
  // LL_TIM_EnableARRPreload(TIM3);
  LL_TIM_CC_EnableChannel(TIM3,LL_TIM_CHANNEL_CH2);
  LL_TIM_EnableCounter(TIM3);

  vkeyKey_Init(KEY0_GPIO_Port, KEY0_Pin, ACTIVE_LOW, &tKey0);
  vkeyKey_Init(KEY1_GPIO_Port, KEY1_Pin, ACTIVE_LOW, &tKey1);
  vusartUSART_Init();
  vusartUSART_StartRX();
  // LL_mDelay(1);
  // vusartUSART_Print("============");
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {        
    /* 接收串口訊息並執行動作*/
    eusartCMD = eusartUSART_Poll();
    switch (eusartCMD)
    {
    case USART_CMD_LED_ON:
        vledLed_On(&LED1);
        vusartUSART_Print("RX test success!!!");
      break;
    case USART_CMD_UNKNOWN:
        vusartUSART_Print("unknown!");
      break;
    default:
        vusartUSART_Print("maybe none or error");
      break;
    }

    vkeyKey_Tick(&tKey0);
    vkeyKey_Tick(&tKey1);
    ekeyEvent0 = ekeyKey_GetEvent(&tKey0);
    ekeyEvent1 = ekeyKey_GetEvent(&tKey1);

    switch (ekeyEvent0)
    {
    case KEY_EVENT_PRESS:
      vledLed_PWM_CCR_Change(0);
      vusartUSART_Print("led toggle");
      break;
    case KEY_EVENT_LONG_PRESS:
      vledLed_PWM_CCR_Change(100);
      break;
    case KEY_EVENT_RELEASE:
      break;  
    default:
      break;
    }

    switch (ekeyEvent1)
    {
    case KEY_EVENT_PRESS:
      vledLed_Toggle(&LED1);  
      break;
    case KEY_EVENT_LONG_PRESS:
      vledLed_Off(&LED1);
      break;
    case KEY_EVENT_RELEASE:
      break;  
    default:
      break;
    }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

/**
  * @brief System Clock Configuration
  * @retval None
  */
void SystemClock_Config(void)
{
  LL_FLASH_SetLatency(LL_FLASH_LATENCY_0);
  while(LL_FLASH_GetLatency()!= LL_FLASH_LATENCY_0)
  {
  }
  LL_RCC_HSI_SetCalibTrimming(16);
  LL_RCC_HSI_Enable();

   /* Wait till HSI is ready */
  while(LL_RCC_HSI_IsReady() != 1)
  {

  }
  LL_RCC_SetAHBPrescaler(LL_RCC_SYSCLK_DIV_1);
  LL_RCC_SetAPB1Prescaler(LL_RCC_APB1_DIV_2);
  LL_RCC_SetAPB2Prescaler(LL_RCC_APB2_DIV_1);
  LL_RCC_SetSysClkSource(LL_RCC_SYS_CLKSOURCE_HSI);

   /* Wait till System clock is ready */
  while(LL_RCC_GetSysClkSource() != LL_RCC_SYS_CLKSOURCE_STATUS_HSI)
  {

  }
  LL_Init1msTick(8000000);
  LL_SetSystemCoreClock(8000000);
}

